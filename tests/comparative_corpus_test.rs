const KNOWN_SPLITS: [&str; 5] = [
    "held_out",
    "in_sample_regression",
    "consumed_for_tuning",
    "vendor_in_sample",
    "unlabelled",
];

fn repo_root() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR"))
}

/// Reads a comparison corpus, refusing to skip a line it cannot parse: a silently
/// shrinking denominator is how a bad number gets published.
fn load_jsonl(path: &Path) -> Vec<Record> {
    let file =
        std::fs::File::open(path).unwrap_or_else(|e| panic!("cannot read {}: {e}", path.display()));
    let mut out = Vec::new();
    for (n, line) in BufReader::new(file).lines().enumerate() {
        let line = line.unwrap_or_else(|e| panic!("{} line {}: {e}", path.display(), n + 1));
        if line.trim().is_empty() {
            continue;
        }
        out.push(serde_json::from_str(&line).unwrap_or_else(|e| {
            panic!(
                "{} line {}: {e} — the record contract changed; fix the ingestor, do not skip it",
                path.display(),
                n + 1
            )
        }));
    }
    out
}

fn load_unified() -> Vec<Record> {
    load_jsonl(&repo_root().join(UNIFIED))
}

fn sha256_of(relative: &str) -> String {
    let bytes = std::fs::read(repo_root().join(relative))
        .unwrap_or_else(|e| panic!("cannot read {relative}: {e}"));
    hex::encode(Sha256::digest(&bytes))
}

/// Warm up once so the first case is not paying for lazy initialisation, mirroring
/// `tests/heldout_v2_measurement_test.rs`.
fn engine() -> SatguardianSatEngine {
    let engine = SatguardianSatEngine::new();
    let _ = engine.evaluate_payload(&HttpRequestPayload::new("GET", "/", "", ""));
    engine
}

/// Times only `evaluate_payload`: no HTTP, no file I/O, no proxy. The number is the engine, not
/// the product, and it belongs to whichever machine ran it — the summary string says so.
fn run(engine: &SatguardianSatEngine, record: &Record) -> (bool, f64) {
    let mut req = HttpRequestPayload::new(
        record.request.method.clone(),
        record.request.path.clone(),
        record.request.query.clone(),
        record.request.body.clone(),
    );
    req.headers = record
        .request
        .headers
        .iter()
        .map(|(k, v)| (k.to_ascii_lowercase(), v.clone()))
        .collect();
    let started = Instant::now();
    let blocked = engine.evaluate_payload(&req).is_violation;
    (blocked, started.elapsed().as_secs_f64() * 1e6)
}

#[derive(Debug, Default)]
struct Tally {
    attacks: usize,
    detected: Vec<String>,
    missed: Vec<String>,
    controls: usize,
    cleared: usize,
    blocked: Vec<String>,
    per_category: BTreeMap<String, (usize, usize)>,
    latency_us: Vec<f64>,
}

impl Tally {
    fn observe(&mut self, record: &Record, blocked: bool, latency_us: f64) {
        self.latency_us.push(latency_us);
        if record.label == "malicious" {
            self.attacks += 1;
            let entry = self
                .per_category
                .entry(record.category.clone())
                .or_insert((0, 0));
            entry.1 += 1;
            if blocked {
                self.detected.push(record.case_id.clone());
                entry.0 += 1;
            } else {
                self.missed.push(record.case_id.clone());
            }
        } else {
            self.controls += 1;
            if blocked {
                self.blocked.push(record.case_id.clone());
            } else {
                self.cleared += 1;
            }
        }
    }

    fn recall(&self) -> f64 {
        self.detected.len() as f64 / self.attacks as f64
    }

    fn fpr(&self) -> f64 {
        self.blocked.len() as f64 / self.controls as f64
    }

    /// Percentiles of in-process engine latency, labelled with the machine that produced them.
    fn latency(&self) -> String {
        let mut lat = self.latency_us.clone();
        lat.sort_by(|a, b| a.partial_cmp(b).unwrap_or(std::cmp::Ordering::Equal));
        let at = |q: f64| lat[((lat.len() as f64 * q).floor() as usize).min(lat.len() - 1)];
        format!(
            "p50 {:.1} us  p90 {:.1} us  p99 {:.1} us  (in-process evaluate_payload only, {} cases, this machine)",
            at(0.50),
            at(0.90),
            at(0.99),
            lat.len()
        )
    }
}

fn tally(records: &[&Record]) -> Tally {
    let engine = engine();
    let mut t = Tally::default();
    for record in records {
        let (blocked, latency_us) = run(&engine, record);
        t.observe(record, blocked, latency_us);
    }
    t
}

/// 95% Wilson score interval, the same one `src/bin/satbench.rs` reports.
fn wilson(successes: usize, total: usize) -> (f64, f64) {
    if total == 0 {
        return (0.0, 0.0);
    }
    let n = total as f64;
    let p = successes as f64 / n;
    let z = 1.959_963_984_f64;
    let denom = 1.0 + z * z / n;
    let centre = (p + z * z / (2.0 * n)) / denom;
    let spread = z * ((p * (1.0 - p) + z * z / (4.0 * n)) / n).sqrt() / denom;
    ((centre - spread).max(0.0), (centre + spread).min(1.0))
}

#[test]
fn unified_comparison_corpus_is_intact() {
    let records = load_unified();
    let mut ids = HashSet::new();
    let mut by_split: BTreeMap<String, usize> = BTreeMap::new();

    for record in &records {
        assert!(
            ids.insert(record.case_id.clone()),
            "duplicate case_id {}",
            record.case_id
        );
        assert!(
            KNOWN_SPLITS.contains(&record.split.as_str()),
            "{}: unknown split {:?} — the harness refuses to guess what a new split licenses",
            record.case_id,
            record.split
        );
        assert!(
            record.label == "malicious" || record.label == "benign",
            "{}: invalid label {:?}",
            record.case_id,
            record.label
        );
        assert!(
            !record.request.path.is_empty()
                || !record.request.query.is_empty()
                || !record.request.body.is_empty()
                || !record.request.headers.is_empty(),
            "{}: empty request",
            record.case_id
        );
        *by_split.entry(record.split.clone()).or_insert(0) += 1;
    }

    assert_eq!(
        by_split.get("held_out"),
        Some(&155),
        "the held-out batch changed size; a shrinking corpus is how an estimate becomes flattering"
    );
    assert_eq!(by_split.get("in_sample_regression"), Some(&79));
    assert_eq!(by_split.get("consumed_for_tuning"), Some(&21));

    for (corpus, expected_sha) in SOURCE_FILES {
        let rows: Vec<&Record> = records.iter().filter(|r| r.corpus == corpus).collect();
        let stored: HashSet<&str> = rows
            .iter()
            .filter_map(|r| r.corpus_sha256.as_deref())
            .collect();
        assert_eq!(
            stored.len(),
            1,
            "{corpus}: {} rows carry {} distinct source digests — records disagree or lost the field",
            rows.len(),
            stored.len()
        );
        assert_eq!(
            rows.iter().filter(|r| r.corpus_sha256.is_none()).count(),
            0,
            "{corpus}: some rows no longer record which source file they came from"
        );
        let stored = *stored.iter().next().unwrap();
        assert_eq!(
            stored, expected_sha,
            "{corpus}: the digest recorded in the corpus no longer matches the published one"
        );
        let file_sha = sha256_of(&format!("corpus/{corpus}.json"));
        assert_eq!(
            stored, file_sha,
            "{corpus}: corpus/{corpus}.json was edited after normalisation — re-run tools/normalize_corpus.py \
             and check whether any number already published from it is still true"
        );
    }
}

#[test]
fn tuning_sets_are_a_regression_floor_not_an_accuracy_claim() {
    let records = load_unified();
    let floor: Vec<&Record> = records
        .iter()
        .filter(|r| r.split == "in_sample_regression" || r.split == "consumed_for_tuning")
        .collect();

    let t = tally(&floor);
    assert_eq!(t.attacks, 80);
    assert_eq!(t.controls, 20);

    assert_eq!(
        t.missed,
        Vec::<String>::new(),
        "the engine regressed on cases it was already fixed against: {:#?}",
        t.missed
    );
    assert_eq!(
        t.blocked,
        Vec::<String>::new(),
        "the engine now blocks benign traffic it used to clear: {:#?}",
        t.blocked
    );

    println!(
        "\nfloor: {}/{} attacks blocked, {}/{} controls blocked — perfect by construction, so it proves \
         only that nothing regressed",
        t.detected.len(),
        t.attacks,
        t.blocked.len(),
        t.controls
    );
    println!("  latency: {}", t.latency());
}

/// The held-out estimate of record is the newest frozen batch. heldout_v2's report stays in
/// `corpus/` as provenance for the 56.1%/7.0% figure it produced, and v3–v9 are now tuning
/// inputs, so this test reproduces v10 — the batch that was labelled before the engine ever saw it.
///
/// v10 has since been spent by the protocol/DSL detector iteration: the engine now detects
/// every case, so `corpus/heldout_v10_report.json` is kept immutable as the honest one-shot
/// measurement (38.6% recall / 0.0% FPR) while `corpus/heldout_v10_post_tuning_report.json`
/// records current behaviour. This test therefore asserts BOTH: the one-shot figures remain
/// intact as provenance, and live engine behaviour still matches the post-tuning diagnostic —
/// so any further unintended change keeps tripping it. Per maintainer decision no
/// heldout_v11 will be produced.
#[test]
fn heldout_v10_reproduction_matches_the_published_report() {
    let published: serde_json::Value = serde_json::from_str(
        &std::fs::read_to_string(repo_root().join("corpus/heldout_v10_report.json"))
            .expect("corpus/heldout_v10_report.json is the committed one-shot measurement"),
    )
    .expect("heldout_v10_report.json is not valid JSON");
    // Provenance guard: the honest one-shot figures must never be rewritten.
    assert_eq!(published["counts"]["detected"].as_u64().unwrap(), 27);
    assert_eq!(published["counts"]["missed"].as_u64().unwrap(), 43);
    assert_eq!(published["counts"]["blocked_controls"].as_u64().unwrap(), 0);

    let post_tuning: serde_json::Value = serde_json::from_str(
        &std::fs::read_to_string(repo_root().join("corpus/heldout_v10_post_tuning_report.json"))
            .expect("corpus/heldout_v10_post_tuning_report.json is the committed diagnostic"),
    )
    .expect("heldout_v10_post_tuning_report.json is not valid JSON");

    let records =
        load_jsonl(&repo_root().join("benchmarks/real_comparative/corpus/heldout_v10.jsonl"));
    assert_eq!(
        records.len(),
        published["counts"]["attacks"].as_u64().unwrap() as usize
            + published["counts"]["controls"].as_u64().unwrap() as usize,
        "the held-out corpus and the published report disagree about how many cases exist"
    );

    let held_out: Vec<&Record> = records.iter().collect();
    let t = tally(&held_out);
    assert_eq!(t.detected.len(), post_tuning["counts"]["detected"].as_u64().unwrap() as usize, concat!(
        "The engine's behaviour on held-out cases changed.\n",
        "That is allowed, but it spends this batch: update corpus/heldout_v10_post_tuning_report.json,\n",
        "STATUS.md and docs/status.md before quoting any v10 figure as current behaviour.\n",
        "The one-shot estimate in corpus/heldout_v10_report.json must remain untouched."
    ));
    assert_eq!(
        t.blocked.len(),
        post_tuning["counts"]["blocked_controls"].as_u64().unwrap() as usize,
        concat!(
        "The false-positive behaviour on held-out controls changed.\n",
        "Update corpus/heldout_v10_post_tuning_report.json and the status documents."
    )
    );
    assert_eq!(
        t.missed.len(),
        post_tuning["counts"]["missed"].as_u64().unwrap() as usize
    );
    assert_eq!(
        t.cleared,
        post_tuning["counts"]["cleared"].as_u64().unwrap() as usize
    );

    let (lo, hi) = wilson(t.detected.len(), t.attacks);
    assert!(
        (t.recall() - post_tuning["recall"]["value"].as_f64().unwrap()).abs() < 1e-12,
        "recall recomputed from the corpus no longer equals the post-tuning diagnostic"
    );
    assert!((lo - post_tuning["recall"]["ci95"][0].as_f64().unwrap()).abs() < 1e-9);
    assert!((hi - post_tuning["recall"]["ci95"][1].as_f64().unwrap()).abs() < 1e-9);

    println!(
        "\nheld-out reproduction: recall={:.4} (95% CI {:.4}..{:.4}) over {} attacks, FPR={:.4} over {} controls",
        t.recall(),
        lo,
        hi,
        t.attacks,
        t.fpr(),
        t.controls
    );
    println!("  latency: {}", t.latency());
}

#[test]
fn vendor_crs_batch_is_measured_only_never_asserted() {
    let path = repo_root().join(CRS_LOCAL);
    if !path.exists() {
        println!(
            "skipped: {} is regenerated by tools/ingest_crs_tests.py and is not checked in",
            path.display()
        );
        return;
    }

    let records = load_jsonl(&path);
    assert_eq!(
        sha256_of(CRS_LOCAL),
        CRS_PINNED_SHA,
        "the local crs_v430.jsonl is not the digest pinned in provenance.json — regenerate it with \
         tools/ingest_crs_tests.py against the pinned CRS commit before reading any number from it"
    );
    let labelled: Vec<&Record> = records
        .iter()
        .filter(|r| r.split == "vendor_in_sample")
        .collect();
    let unlabelled = records.iter().filter(|r| r.split == "unlabelled").count();
    assert_eq!(
        records.len() - labelled.len(),
        unlabelled,
        "CRS rows carry a split the harness does not recognise"
    );
    assert_eq!(
        labelled.len(),
        4050,
        "the vendor batch lost labelled cases — the 4 files Defender refuses are the known cause"
    );

    let t = tally(&labelled);
    let (lo, hi) = wilson(t.detected.len(), t.attacks);
    println!(
        "\nCRS v4.30.0 vendor in-sample: {}/{} = recall {:.4} (95% CI {:.4}..{:.4}).\n\
         This is the rule set's own test suite: near-perfect by construction, not a comparison result.",
        t.detected.len(),
        t.attacks,
        t.recall(),
        lo,
        hi
    );
    println!(
        "  {} unlabelled stages scored by no engine; {}",
        unlabelled,
        t.latency()
    );
    for group in [&t.missed[..], &t.blocked[..]] {
        for case_id in group.iter().take(20) {
            println!("  {case_id}");
        }
    }
    assert!(
        t.attacks != 0,
        "crs_v430.jsonl has records but none carry a vendor_in_sample label — re-run the ingestor"
    );
}
