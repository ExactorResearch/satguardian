//! In-process unit tests for the comparison corpus used by `benchmarks/real_comparative`.
//!
//! Everything here calls `SatguardianSatEngine::evaluate_payload` directly. No HTTP, no proxy, no
//! deployed host: a measurement that travelled through a network stack would include latency,
//! TLS and routing that the engine does not control, and it would touch live data.
//!
//! These tests assert the shape of the corpus and reproduce published numbers. They deliberately
//! do not assert detection *quality* on the held-out batch: a held-out estimate only stays honest
//! if the run that produces it cannot fail into a fix and be re-measured. The held-out test below
//! is a tripwire for that — see the message it prints when it fails.

use satguardian_waf::engine::SatguardianSatEngine;
use satguardian_waf::types::HttpRequestPayload;
use serde::Deserialize;
use sha2::{Digest, Sha256};
use std::collections::{BTreeMap, HashMap, HashSet};
use std::io::{BufRead, BufReader};
use std::path::{Path, PathBuf};
use std::time::Instant;

#[derive(Debug, Deserialize)]
struct Record {
    case_id: String,
    corpus: String,
    /// Absent on vendor rows, which carry a pinned `vendor_source` instead of a local file digest.
    #[serde(default)]
    corpus_sha256: Option<String>,
    label: String,
    category: String,
    split: String,
    request: RequestSpec,
}

#[derive(Debug, Deserialize)]
struct RequestSpec {
    method: String,
    path: String,
    query: String,
    body: String,
    #[serde(default)]
    headers: HashMap<String, String>,
}

const UNIFIED: &str = "benchmarks/real_comparative/corpus/unified_v1.jsonl";

